SkyBox::~SkyBox()
{
    if (skyboxVAO)
        glDeleteVertexArrays(1, &skyboxVAO);
    if (skyboxVBO)
        glDeleteBuffers(1, &skyboxVBO);
    // glDeleteTextures(1, &cubemapTexture);
}

SkyBox::SkyBox(Shader *skyBoxShader, unsigned int cubemapTexture) : cubemapTexture(cubemapTexture)
{

    this->shader = skyBoxShader;

    glGenVertexArrays(1, &skyboxVAO);
    glGenBuffers(1, &skyboxVBO);
    glBindVertexArray(skyboxVAO);
    glBindBuffer(GL_ARRAY_BUFFER, skyboxVBO);
    glBufferData(GL_ARRAY_BUFFER, sizeof(skyboxVertices), &skyboxVertices, GL_STATIC_DRAW);
    glEnableVertexAttribArray(0);
    glVertexAttribPointer(0, 3, GL_FLOAT, GL_FALSE, 3 * sizeof(float), (void *)0);
}

void SkyBox::drawSkybox(glm::mat4 view, glm::mat4 proj, __attribute__((unused)) glm::vec3 pos)
{
    glDepthMask(GL_FALSE);
    shader->Use();
    shader->SetInt("skybox", 0);

    glm::mat4 matrix = proj * glm::mat4(glm::mat3(view));

    shader->Setmat4("matrix", matrix);

    glBindVertexArray(skyboxVAO);
    glActiveTexture(GL_TEXTURE0);
    glBindTexture(GL_TEXTURE_CUBE_MAP, cubemapTexture);
    glDrawArrays(GL_TRIANGLES, 0, 36);
    glBindVertexArray(0);
    glDepthMask(GL_TRUE);
}

